#!/usr/bin/env python3
"""Build a richer teacher initialization library from SD/TVA audits.

This is an offline conversion step.  Candidate rules are assumed to have been
generated by SD rollout plus TVA terminal compensation, then audited on
high-quality and contrast trace sets.  The script does not hard-code retained
rule identities; it selects rules by support, counterfactual rank, reliability,
and low-score contrast status.
"""

from __future__ import annotations

import argparse
import json
import math
from collections import Counter
from datetime import datetime, timezone
from pathlib import Path
from typing import Any


OPPOSITE_ACTION = {
    "waist_pos": "waist_neg",
    "waist_neg": "waist_pos",
    "hip_pos": "hip_neg",
    "hip_neg": "hip_pos",
    "knee_pos": "knee_neg",
    "knee_neg": "knee_pos",
    "ankle_pos": "ankle_neg",
    "ankle_neg": "ankle_pos",
}


def load_json(path: Path) -> dict[str, Any]:
    return json.loads(path.read_text(encoding="utf-8"))


def write_json(path: Path, payload: dict[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(payload, ensure_ascii=False, indent=2, sort_keys=True) + "\n", encoding="utf-8")


def audit_by_rule(path: Path | None) -> dict[tuple[str, str], dict[str, Any]]:
    if path is None or not path.exists():
        return {}
    payload = load_json(path)
    out: dict[tuple[str, str], dict[str, Any]] = {}
    for row in payload.get("rules_report", []):
        out[(str(row.get("rule_key")), str(row.get("action_family")))] = row
    return out


def source_rule_map(payload: dict[str, Any]) -> dict[tuple[str, str], dict[str, Any]]:
    return {
        (str(rule.get("rule_key")), str(rule.get("action_family"))): rule
        for rule in payload.get("rules", [])
    }


def finite_float(value: Any, default: float = 0.0) -> float:
    try:
        out = float(value)
    except (TypeError, ValueError):
        return default
    return out if math.isfinite(out) else default


def score_candidate(rule: dict[str, Any], high: dict[str, Any] | None, low: dict[str, Any] | None) -> float:
    high_top3 = finite_float((high or {}).get("target_joint_top3_rate"), finite_float(rule.get("joint_top3_rate")))
    high_best = finite_float((high or {}).get("target_joint_best_rate"), finite_float(rule.get("joint_best_rate")))
    source_top3 = finite_float(rule.get("joint_top3_rate"))
    good = finite_float(rule.get("good_outcome_rate"))
    entropy = finite_float(rule.get("best_family_entropy"), 1.0)
    low_top3 = finite_float((low or {}).get("target_joint_top3_rate"))
    low_penalty = 0.15 * low_top3 if (low or {}).get("status") == "supported" else 0.05 * low_top3
    return 0.35 * high_top3 + 0.20 * high_best + 0.20 * source_top3 + 0.15 * good + 0.10 * (1.0 - entropy) - low_penalty


def confidence_from_evidence(rule: dict[str, Any], high: dict[str, Any] | None, low: dict[str, Any] | None) -> float:
    high_top3 = finite_float((high or {}).get("target_joint_top3_rate"), finite_float(rule.get("joint_top3_rate")))
    high_best = finite_float((high or {}).get("target_joint_best_rate"), finite_float(rule.get("joint_best_rate")))
    source_top3 = finite_float(rule.get("joint_top3_rate"))
    entropy = finite_float(rule.get("best_family_entropy"), 1.0)
    low_status = (low or {}).get("status", "missing")
    low_top3 = finite_float((low or {}).get("target_joint_top3_rate"))
    low_discount = 0.10 * low_top3 if low_status == "supported" else 0.03 * low_top3
    confidence = 0.62 + 0.16 * high_top3 + 0.08 * high_best + 0.08 * source_top3 + 0.06 * (1.0 - entropy) - low_discount
    return max(0.55, min(0.98, confidence))


def decision_for_rule(rule: dict[str, Any], high: dict[str, Any] | None, low: dict[str, Any] | None, args: argparse.Namespace) -> tuple[str, list[str]]:
    notes: list[str] = []
    high_status = (high or {}).get("status", "missing")
    low_status = (low or {}).get("status", "missing")
    source_top3 = finite_float(rule.get("joint_top3_rate"))
    source_best = finite_float(rule.get("joint_best_rate"))
    high_top3 = finite_float((high or {}).get("target_joint_top3_rate"), source_top3)
    context_support = int(rule.get("context_support", 0) or rule.get("support", 0) or 0)
    cf_records = int(rule.get("num_counterfactual_records", 0) or 0)

    if context_support < args.min_context_support:
        notes.append("source context support below threshold")
    if cf_records < args.min_counterfactual_records:
        notes.append("counterfactual sample count below threshold")
    if source_top3 < args.min_source_top3:
        notes.append("source joint top-3 rate below threshold")
    if source_best < args.min_source_best:
        notes.append("source joint best rate below threshold")
    if high_status not in set(args.allowed_high_status):
        notes.append(f"high-quality reliability status is {high_status}")
    if high_top3 < args.min_high_top3:
        notes.append("high-quality audit top-3 rate below threshold")
    if low_status in set(args.blocking_low_status):
        notes.append(f"low-score contrast status is blocking: {low_status}")

    if notes:
        return "observe", notes
    return "active", ["selected by support, high-quality reliability, and low-score contrast filters"]


def as_online_rule(
    rule: dict[str, Any],
    high: dict[str, Any] | None,
    low: dict[str, Any] | None,
    selection_decision: str,
    selection_notes: list[str],
    args: argparse.Namespace,
) -> dict[str, Any]:
    key = str(rule["rule_key"])
    family = str(rule["action_family"])
    confidence = confidence_from_evidence(rule, high, low)
    status = "confidence_active" if selection_decision == "active" else "confidence_observing"
    return {
        "id": f"sd_tva_rich_context|{key}->prefer:{family}",
        "substate_key": key,
        "rule_key": key,
        "state_event": "broad_transition_context",
        "substate_predicate": key,
        "rule_role": "broad_transition_context",
        "action_family": family,
        "opposite_action_family": OPPOSITE_ACTION.get(family, ""),
        "intervention_type": "soft_prefer_action_family",
        "source": "sd_tva_broad_context_counterfactual",
        "rule_origin": args.rule_origin,
        "teacher_source": "rich_sd_tva_counterfactual_high_quality_contexts",
        "status": status,
        "confidence_status": status,
        "confidence": confidence,
        "effective_prior_scale": confidence,
        "support": int(rule.get("support", 0) or 0),
        "context_support": int(rule.get("context_support", 0) or rule.get("support", 0) or 0),
        "num_counterfactual_records": int(rule.get("num_counterfactual_records", 0) or 0),
        "joint_top3_rate": finite_float(rule.get("joint_top3_rate")),
        "joint_best_rate": finite_float(rule.get("joint_best_rate")),
        "best_family_entropy": finite_float(rule.get("best_family_entropy")),
        "good_outcome_rate": finite_float(rule.get("good_outcome_rate")),
        "selection_score": score_candidate(rule, high, low),
        "selection_decision": selection_decision,
        "selection_notes": selection_notes,
        "retention_decision": "retain" if selection_decision == "active" else "observe",
        "online_thresholds": {
            "selection": "dynamic rich teacher selection from SD/TVA reliability audits",
            "min_context_support": args.min_context_support,
            "min_counterfactual_records": args.min_counterfactual_records,
            "min_source_top3": args.min_source_top3,
            "min_source_best": args.min_source_best,
            "min_high_top3": args.min_high_top3,
            "allowed_high_status": args.allowed_high_status,
            "blocking_low_status": args.blocking_low_status,
        },
        "reliability_audits": {
            "high_quality": high,
            "low_score_contrast": low,
        },
        "audit_notes": [
            "该规则由高质量轨迹上下文中的 SD/TVA 联合反事实排名生成。",
            "该脚本只生成初始化教师规则库，不修改在线训练过程。",
            "教师规则保护只应阻止弱证据过早降权；强反例仍可通过信心机制削弱规则。",
        ],
    }


def run(args: argparse.Namespace) -> dict[str, Any]:
    candidates = load_json(args.candidates)
    high = audit_by_rule(args.high_audit)
    low = audit_by_rule(args.low_audit)
    generated = source_rule_map(candidates)

    rows: list[tuple[float, dict[str, Any]]] = []
    for item, rule in generated.items():
        h = high.get(item)
        l = low.get(item)
        decision, notes = decision_for_rule(rule, h, l, args)
        online = as_online_rule(rule, h, l, decision, notes, args)
        rows.append((online["selection_score"], online))

    rows.sort(key=lambda item: (item[1]["selection_decision"] == "active", item[0], item[1]["context_support"]), reverse=True)
    active = [row for _score, row in rows if row["selection_decision"] == "active"][: args.max_active_rules]
    observing = [row for _score, row in rows if row["selection_decision"] != "active"][: args.max_observing_rules]
    rules = active + observing

    return {
        "library_version": "counterfactual_teacher_rich_init_confidence_v1",
        "rule_family": "sd_tva_broad_context_counterfactual_teacher_rich_init",
        "created_at_utc": datetime.now(timezone.utc).isoformat(),
        "online_enabled": bool(active),
        "compatibility": {
            "online_prior": "online_rule_prior_v6",
            "requires_temporal_simple_phase": True,
            "source": "sd_tva_broad_context_counterfactual",
            "protected_rule_origin": args.rule_origin,
        },
        "source_candidates": str(args.candidates),
        "source_audits": {
            "high_quality": str(args.high_audit) if args.high_audit else None,
            "low_score_contrast": str(args.low_audit) if args.low_audit else None,
        },
        "selection": {
            "policy": "retain all high-quality SD/TVA-supported rules up to a configurable active cap; keep near misses as observing",
            "num_generated_candidates": len(generated),
            "num_active": len(active),
            "num_observing": len(observing),
            "max_active_rules": args.max_active_rules,
            "max_observing_rules": args.max_observing_rules,
        },
        "status_counts": dict(Counter(rule["confidence_status"] for rule in rules)),
        "num_rules": len(rules),
        "rules": rules,
    }


def write_markdown(path: Path, payload: dict[str, Any]) -> None:
    lines = [
        "# Counterfactual Teacher Rich Initialization Library",
        "",
        f"- Created: `{payload['created_at_utc']}`",
        f"- Rules: `{payload['num_rules']}`",
        f"- Status counts: `{payload['status_counts']}`",
        f"- Source: `{payload['source_candidates']}`",
        "",
        "| status | rule | action | score | confidence | ctx | top3 | best | high audit | low audit | notes |",
        "|---|---|---|---:|---:|---:|---:|---:|---|---|---|",
    ]
    for rule in payload["rules"]:
        high = (rule.get("reliability_audits", {}).get("high_quality") or {}).get("status", "missing")
        low = (rule.get("reliability_audits", {}).get("low_score_contrast") or {}).get("status", "missing")
        notes = "; ".join(rule.get("selection_notes", [])[:2])
        lines.append(
            f"| `{rule['confidence_status']}` | `{rule['rule_key']}` | `{rule['action_family']}` | "
            f"{rule['selection_score']:.3f} | {rule['confidence']:.3f} | {rule['context_support']} | "
            f"{rule['joint_top3_rate']:.3f} | {rule['joint_best_rate']:.3f} | `{high}` | `{low}` | {notes} |"
        )
    path.with_suffix(".md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--candidates", type=Path, required=True)
    parser.add_argument("--high-audit", type=Path)
    parser.add_argument("--low-audit", type=Path)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--rule-origin", default="sd_tva_counterfactual_teacher_rich_init_v1")
    parser.add_argument("--allowed-high-status", action="append", default=["supported"])
    parser.add_argument("--blocking-low-status", action="append", default=["supported"])
    parser.add_argument("--min-context-support", type=int, default=40)
    parser.add_argument("--min-counterfactual-records", type=int, default=40)
    parser.add_argument("--min-source-top3", type=float, default=0.60)
    parser.add_argument("--min-source-best", type=float, default=0.10)
    parser.add_argument("--min-high-top3", type=float, default=0.60)
    parser.add_argument("--max-active-rules", type=int, default=24)
    parser.add_argument("--max-observing-rules", type=int, default=24)
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    payload = run(args)
    write_json(args.output, payload)
    write_markdown(args.output, payload)
    print(f"wrote rich teacher library: {args.output}")
    print(f"rules={payload['num_rules']} status_counts={payload['status_counts']}")


if __name__ == "__main__":
    main()
