#!/usr/bin/env python3
"""Build an online initialization library from retained SD/TVA teacher rules.

The retained set is intentionally narrow: candidates are generated by joint
SD rollout plus TVA terminal compensation, then filtered by the reliability
audits kept with the teacher-core artifacts.  This script only converts the
audited retained rules into the online rule-library schema.
"""

from __future__ import annotations

import argparse
import json
from datetime import datetime, timezone
from pathlib import Path
from typing import Any


DEFAULT_ROOT = Path("results/sd_retrospective_rule_induction/teacher_core/hopper_teacher_transition_context_v1")
DEFAULT_CANDIDATES = DEFAULT_ROOT / "counterfactual_generated_teacher_simple_v1_broad_context_cycle_v1.json"
DEFAULT_LOW_AUDIT = DEFAULT_ROOT / "reliability_low_strict_minrepro_100k_cycle040_sdtva.json"
DEFAULT_HIGH_AUDIT = DEFAULT_ROOT / "reliability_high_teacher_cycle035_sdtva.json"
DEFAULT_OUTPUT = DEFAULT_ROOT / "library_counterfactual_teacher_retain8_confidence.json"

RETAINED_RULES = {
    ("prev=ground_front|cur=air_rising|omega=omega_nonneg|vx=vx_high|support=support_none", "hip_neg"),
    ("prev=ground_front|cur=other|omega=omega_nonneg|vx=vx_high|support=support_none", "hip_neg"),
    ("prev=air_falling|cur=air_falling|omega=omega_nonneg|vx=vx_high|support=support_none", "hip_neg"),
    ("prev=air_falling|cur=ground_front|omega=omega_neg|vx=vx_high|support=support_full", "knee_neg"),
    ("prev=air_falling|cur=ground_front|omega=omega_neg|vx=vx_high|support=support_partial", "knee_neg"),
    ("prev=air_falling|cur=ground_front|omega=omega_nonneg|vx=vx_high|support=support_none", "hip_neg"),
    ("prev=air_falling|cur=ground_front|omega=omega_nonneg|vx=vx_high|support=support_full", "hip_pos"),
    ("prev=ground_front|cur=ground_front|omega=omega_nonneg|vx=vx_high|support=support_partial", "hip_pos"),
}

OPPOSITE_ACTION = {
    "waist_pos": "waist_neg",
    "waist_neg": "waist_pos",
    "hip_pos": "hip_neg",
    "hip_neg": "hip_pos",
    "knee_pos": "knee_neg",
    "knee_neg": "knee_pos",
    "ankle_pos": "ankle_neg",
    "ankle_neg": "ankle_pos",
}


def load_json(path: Path) -> dict[str, Any]:
    return json.loads(path.read_text(encoding="utf-8"))


def write_json(path: Path, payload: dict[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(payload, ensure_ascii=False, indent=2, sort_keys=True) + "\n", encoding="utf-8")


def audit_by_rule(path: Path) -> dict[tuple[str, str], dict[str, Any]]:
    payload = load_json(path)
    out: dict[tuple[str, str], dict[str, Any]] = {}
    for row in payload.get("rules_report", []):
        out[(str(row.get("rule_key")), str(row.get("action_family")))] = row
    return out


def as_online_rule(rule: dict[str, Any], high_audit: dict[str, Any] | None, low_audit: dict[str, Any] | None) -> dict[str, Any]:
    key = str(rule["rule_key"])
    family = str(rule["action_family"])
    source_support = int(rule.get("context_support", 0) or rule.get("support", 0) or 0)
    joint_top3 = float(rule.get("joint_top3_rate", 0.0) or 0.0)
    joint_best = float(rule.get("joint_best_rate", 0.0) or 0.0)
    confidence = max(0.70, min(1.0, 0.70 + 0.20 * joint_top3 + 0.10 * joint_best))
    return {
        "id": f"sd_tva_broad_context|{key}->prefer:{family}",
        "substate_key": key,
        "rule_key": key,
        "state_event": "broad_transition_context",
        "substate_predicate": key,
        "rule_role": "broad_transition_context",
        "action_family": family,
        "opposite_action_family": OPPOSITE_ACTION.get(family, ""),
        "intervention_type": "soft_prefer_action_family",
        "source": "sd_tva_broad_context_counterfactual",
        "rule_origin": "sd_tva_counterfactual_teacher_core_v1",
        "teacher_source": "sd_rollout_tva_terminal_counterfactual_high_quality_contexts",
        "status": "confidence_active",
        "confidence_status": "confidence_active",
        "confidence": confidence,
        "effective_prior_scale": confidence,
        "support": source_support,
        "context_support": source_support,
        "joint_top3_rate": joint_top3,
        "joint_best_rate": joint_best,
        "mean_joint_margin_to_best": rule.get("mean_joint_margin_to_best"),
        "retention_decision": "retain",
        "online_thresholds": {
            "retention": "retained by high-quality stability plus low-score contrast audit",
            "source": "SD rollout return + TVA terminal value",
        },
        "reliability_audits": {
            "high_teacher_cycle035_sdtva": high_audit,
            "low_strict_minrepro_100k_cycle040_sdtva": low_audit,
        },
        "audit_notes": [
            "该规则由 SD/TVA 联合反事实评分自动生成，并经可靠性审计后作为教师初始化规则保留。",
            "教师规则保护只阻止弱证据下的过早冲突降级，强负证据仍可通过信心机制削弱规则。",
        ],
    }


def write_markdown(path: Path, payload: dict[str, Any]) -> None:
    lines = [
        "# Counterfactual Teacher Retain-8 Initialization Library",
        "",
        f"- Created: `{payload['created_at_utc']}`",
        f"- Rules: `{payload['num_rules']}`",
        f"- Source: `{payload['source_candidates']}`",
        "",
        "| rule | action | confidence | high audit | low audit |",
        "|---|---|---:|---|---|",
    ]
    for rule in payload["rules"]:
        high = (rule.get("reliability_audits", {}).get("high_teacher_cycle035_sdtva") or {}).get("status", "missing")
        low = (rule.get("reliability_audits", {}).get("low_strict_minrepro_100k_cycle040_sdtva") or {}).get("status", "missing")
        lines.append(
            f"| `{rule['rule_key']}` | `{rule['action_family']}` | {rule['confidence']:.3f} | `{high}` | `{low}` |"
        )
    path.with_suffix(".md").write_text("\n".join(lines), encoding="utf-8")


def run(args: argparse.Namespace) -> dict[str, Any]:
    candidates = load_json(args.candidates)
    high = audit_by_rule(args.high_audit)
    low = audit_by_rule(args.low_audit)
    generated = {
        (str(rule.get("rule_key")), str(rule.get("action_family"))): rule
        for rule in candidates.get("rules", [])
    }
    missing = sorted(RETAINED_RULES.difference(generated))
    if missing:
        raise ValueError(f"retained rules missing from generated candidates: {missing}")
    rules = [
        as_online_rule(generated[item], high.get(item), low.get(item))
        for item in sorted(RETAINED_RULES)
    ]
    return {
        "library_version": "counterfactual_teacher_retain8_confidence_v1",
        "rule_family": "sd_tva_broad_context_counterfactual_teacher_init",
        "created_at_utc": datetime.now(timezone.utc).isoformat(),
        "online_enabled": True,
        "compatibility": {
            "online_prior": "online_rule_prior_v6",
            "requires_temporal_simple_phase": True,
            "source": "sd_tva_broad_context_counterfactual",
            "protected_rule_origin": "sd_tva_counterfactual_teacher_core_v1",
        },
        "source_candidates": str(args.candidates),
        "source_audits": {
            "high_teacher_cycle035_sdtva": str(args.high_audit),
            "low_strict_minrepro_100k_cycle040_sdtva": str(args.low_audit),
        },
        "selection": {
            "policy": "retain explicit SD/TVA reliability-screened teacher core rules",
            "num_retained": len(rules),
        },
        "status_meaning": {
            "confidence_active": "online-readable teacher rule with confidence-weighted prior scale",
            "confidence_observing": "tracked but not active unless allowed by run config",
            "confidence_retired": "retired by accumulated evidence",
        },
        "num_rules": len(rules),
        "rules": rules,
    }


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--candidates", type=Path, default=DEFAULT_CANDIDATES)
    parser.add_argument("--high-audit", type=Path, default=DEFAULT_HIGH_AUDIT)
    parser.add_argument("--low-audit", type=Path, default=DEFAULT_LOW_AUDIT)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    payload = run(args)
    write_json(args.output, payload)
    write_markdown(args.output, payload)
    print(f"wrote library: {args.output}")
    print(f"rules: {payload['num_rules']}")


if __name__ == "__main__":
    main()
